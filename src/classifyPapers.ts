export const CLASSIFIER_FINGERPRINT = createHash("sha256")
  .update(JSON.stringify({ schema, decisionPolicy: "jev-only-v1" }))
  .digest("hex");

function requiredColumn(data: WorkbookData, header: string): number {
  const index = data.columns.findIndex((column) => column.header === header);
  if (index < 0) throw new Error(`Falta la columna "${header}" en la pestaña ${data.sheetName}.`);
  return index;
}

export function selectPapers(data: WorkbookData): PaperInput[] {
  const idColumn = requiredColumn(data, "arxiv_id");
  const titleColumn = requiredColumn(data, "title");
  const abstractColumn = requiredColumn(data, "abstract");
  const rows = data.rows.filter((row) => row.excelRow >= FIRST_ROW && row.excelRow <= LAST_ROW);
  if (rows.length !== LAST_ROW - FIRST_ROW + 1) {
    throw new Error(`Se esperaban ${LAST_ROW - FIRST_ROW + 1} filas entre ${FIRST_ROW} y ${LAST_ROW}; se encontraron ${rows.length}.`);
  }
  return rows.map((row) => {
    const title = String(row.values[titleColumn] ?? "").trim();
    const abstract = String(row.values[abstractColumn] ?? "").trim();
    if (!title || !abstract) throw new Error(`Falta title o abstract en la fila ${row.excelRow}.`);
    const contentHash = createHash("sha256").update(JSON.stringify({ title, abstract })).digest("hex");
    return {
      excelRow: row.excelRow,
      arxivId: String(row.values[idColumn] ?? ""),
      title,
      abstract,
      contentHash,
    };
  });
}

function choice<K extends string>(answer: JevAnswer | undefined, options: readonly K[]): K {
  if (answer?.type !== "choice" || !options.includes(answer.choice as K)) {
    throw new Error("Jev devolvió una opción inesperada.");
  }
  return answer.choice as K;
}

function chosenProbability(answer: JevAnswer | undefined): number {
  if (answer?.type !== "choice") throw new Error("Jev no devolvió una respuesta de tipo choice.");
  return answer.probabilities[answer.choice];
}

export async function classifyPaper(paper: PaperInput, classifier: JevClassifier): Promise<PaperClassification> {
  let response: Awaited<ReturnType<JevClassifier["classify"]>>;
  for (let attempt = 0; ; attempt += 1) {
    try {
      response = await classifier.classify(schema, { title: paper.title, abstract: paper.abstract });
      break;
    } catch (error) {
      const retryable = error instanceof JevApiError && [429, 500, 502, 503, 504].includes(error.status);
      if (!retryable || attempt >= 3) throw error;
      await sleep(500 * 2 ** attempt);
    }
  }
  const answers = response.answers;
  const modelDecision = choice(answers.decision, ["include", "maybe", "exclude"] as const);
  const overall = answers.decision;
  if (overall.type !== "choice") throw new Error("Jev no devolvió una decisión de tipo choice.");
  const criteria = {
    english: choice(answers.english, ["yes", "no", "unclear"] as const),
    journalOrConference: choice(answers.journalOrConference, ["yes", "no", "unclear"] as const),
    evaluatesAiCoding: choice(answers.evaluatesAiCoding, ["yes", "no", "unclear"] as const),
    empirical: choice(answers.empirical, ["yes", "no", "unclear"] as const),
    focus: choice(answers.focus, ["evaluation", "solution", "unclear"] as const),
  };
  const criterionProbabilities = {
    english: chosenProbability(answers.english),
    journalOrConference: chosenProbability(answers.journalOrConference),
    evaluatesAiCoding: chosenProbability(answers.evaluatesAiCoding),
    empirical: chosenProbability(answers.empirical),
    focus: chosenProbability(answers.focus),
  };
  const probabilities = {
    include: overall.probabilities.include,
    maybe: overall.probabilities.maybe,
    exclude: overall.probabilities.exclude,
  };
  return {
    excelRow: paper.excelRow,
    arxivId: paper.arxivId,
    title: paper.title,
    contentHash: paper.contentHash,
    classification: LABELS[modelDecision],
    decision: modelDecision,
    decisionSource: "jev",
    classifierFingerprint: CLASSIFIER_FINGERPRINT,
    modelDecision,
    modelConfidence: overall.confidence,
    criteria,
    criterionProbabilities,
    probabilities,
    model: response.model,
    usage: response.usage,
  };
}

async function loadPrevious(): Promise<ResultFile | undefined> {
  try {
    return JSON.parse(await readFile(OUTPUT_PATH, "utf8")) as ResultFile;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}

async function saveResults(data: ResultFile): Promise<void> {
  const tempPath = `${OUTPUT_PATH}.tmp`;
  await writeFile(tempPath, `${JSON.stringify(data, null, 2)}\n`);
  await rename(tempPath, OUTPUT_PATH);
}

async function main(): Promise<void> {
  const dryRun = process.argv.includes("--dry-run");
  const force = process.argv.includes("--force");
  const data = await readLocalWorkbook();
  const papers = selectPapers(data);
  if (dryRun) {
    for (const paper of papers) console.log(`${paper.excelRow}\t${paper.arxivId}\t${paper.title}`);
    console.log(`Total: ${papers.length} rows (${FIRST_ROW}-${LAST_ROW}).`);
    return;
  }

  const previous = await loadPrevious();
  const results = previous?.sourceFile === data.filePath && previous.sheetName === data.sheetName
    ? previous.results.filter((result) => papers.some((paper) =>
      paper.excelRow === result.excelRow && paper.contentHash === result.contentHash &&
      result.classifierFingerprint === CLASSIFIER_FINGERPRINT && result.model === (process.env.JEV_MODEL ?? "jev-latest"),
    ))
    : [];
  if (results.length > 0) {
    await writeClassifications(data.filePath, data.sheetName, results);
  }
  const classifier = new JevClassifier();
  for (const paper of papers) {
    if (!force && results.some((result) => result.excelRow === paper.excelRow)) continue;
    console.log(`Classifying row ${paper.excelRow} (${paper.arxivId})...`);
    const result = await classifyPaper(paper, classifier);
    const existingIndex = results.findIndex((item) => item.excelRow === paper.excelRow);
    if (existingIndex >= 0) results[existingIndex] = result;
    else results.push(result);
    results.sort((a, b) => a.excelRow - b.excelRow);
    await saveResults({
      sourceFile: data.filePath,
      sheetName: data.sheetName,
      firstRow: FIRST_ROW,
      lastRow: LAST_ROW,
      results,
    });
    await writeClassifications(data.filePath, data.sheetName, results);
    console.log(`Row ${paper.excelRow}: ${result.classification}`);
  }
  console.log(`Results saved to column J and ${OUTPUT_PATH} (${results.length}/${papers.length} rows).`);
}

if (process.argv[1]?.endsWith("classifyPapers.js")) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
